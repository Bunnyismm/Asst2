CONSTANTS = {
    "SEMESTERS_PER_YEAR": 2,
    "MONTHS_PER_YEAR": 9,
    "CLASS_DAYS_PER_SEMESTER": 75,
    "CS1430_CREDITS": 3,
    "CS1430_MEETINGS_PER_SEMESTER": 45,
}

FUNCTIONS = [
    # (name, number of parameters)
    ("cost_per_semester", 1),
    ("cost_per_month", 1),
    ("cost_per_day", 1),
    ("cost_per_credit", 2),
    ("cost_per_class", 2),
]

# (annual cost, credits this semester). The first pair is the guide's example.
TEST_PAIRS = [(14601, 15), (24000, 12), (9876.54, 17)]

TOLERANCE = 0.005  # half a cent


def expected(name, cost, credits):
    """The right answers, unrounded."""
    if name == "cost_per_semester":
        return cost / 2
    if name == "cost_per_month":
        return cost / 9
    if name == "cost_per_day":
        return cost / (2 * 75)
    if name == "cost_per_credit":
        return cost / (2 * credits)
    if name == "cost_per_class":
        return cost / (2 * credits) * 3 / 45
    raise ValueError(name)


def common_mistake(name, cost, credits, got):
    """If a wrong answer matches a known mistake, explain it."""
    guesses = {
        "cost_per_semester": [
            (cost, "That is the whole year. A year has SEMESTERS_PER_YEAR semesters."),
        ],
        "cost_per_month": [
            (cost / 12, "That uses a 12-month year. The academic year is MONTHS_PER_YEAR months."),
            (cost / 2 / 9, "That spreads one semester over 9 months. Use the whole year's cost."),
        ],
        "cost_per_day": [
            (cost / 365, "That uses 365 calendar days. A day here means a class day."),
            (cost / 75, "That is a full year over one semester's class days. A year has two semesters."),
            (cost / 2 / 5, "That uses 5 days. CLASS_DAYS_PER_SEMESTER is the number of class days."),
        ],
        "cost_per_credit": [
            (cost / credits, "That is the whole year over one semester's credits. Use one semester's cost."),
        ],
        "cost_per_class": [
            (cost / (2 * credits) / 45, "That is one credit over 45 meetings. CS 1430 is CS1430_CREDITS credits."),
            (cost / 2 / 45, "That is the whole semester over 45 meetings. Use only CS 1430's share of the semester."),
            (cost / (2 * credits) * 3, "That is what all of CS 1430 costs for the semester. Divide by the meetings."),
        ],
    }
    for value, hint in guesses.get(name, []):
        if abs(got - value) <= TOLERANCE:
            return hint
    return None


def money(x):
    return "{:.2f}".format(x)


def show_pair(cost, credits, name):
    c = ("{:.2f}".format(cost)).rstrip("0").rstrip(".")
    if dict(FUNCTIONS)[name] == 1:
        return "annual_cost = {}".format(c)
    return "annual_cost = {}, credits = {}".format(c, credits)


