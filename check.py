def child_env():
    env = dict(os.environ)
    env["PYTHONIOENCODING"] = "utf-8"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return env


def run_program(lines):
    """Run main.py with these lines typed in. Returns (status, stdout, stderr)."""
    typed = "\n".join(lines) + "\n"
    try:
        p = subprocess.run(
            [sys.executable, MAIN], input=typed, capture_output=True, text=True,
            encoding="utf-8", errors="replace", cwd=HERE, env=child_env(), timeout=RUN_SECONDS,
        )
    except subprocess.TimeoutExpired as e:
        out = e.stdout.decode("utf-8", "replace") if isinstance(e.stdout, bytes) else (e.stdout or "")
        return "timeout", out, ""
    return ("ok" if p.returncode == 0 else "error"), p.stdout, p.stderr


FUNCTION_PROBE = r'''
import importlib, json, sys, traceback
sys.path.insert(0, sys.argv[1])
cases = json.loads(sys.argv[2])
report = {"import": "ok", "detail": "", "functions": {}}
try:
    m = importlib.import_module("main")
except EOFError:
    report["import"] = "asked_for_input"
except BaseException as e:
    report["import"] = "error"
    report["detail"] = traceback.format_exception_only(type(e), e)[-1].strip()
else:
    for name, args_list in cases.items():
        f = getattr(m, name, None)
        entry = {"exists": callable(f), "results": []}
        if callable(f):
            for args in args_list:
                try:
                    v = f(*args)
                    if isinstance(v, bool):
                        entry["results"].append({"kind": "other", "repr": repr(v)})
                    elif isinstance(v, (int, float)):
                        entry["results"].append({"kind": "number", "value": float(v)})
                    elif v is None:
                        entry["results"].append({"kind": "none"})
                    elif isinstance(v, str):
                        entry["results"].append({"kind": "text", "repr": repr(v)})
                    else:
                        entry["results"].append({"kind": "other", "repr": repr(v)})
                except BaseException as e:
                    entry["results"].append({"kind": "crash",
                        "repr": traceback.format_exception_only(type(e), e)[-1].strip()})
        report["functions"][name] = entry
print()
print("@@REPORT@@" + json.dumps(report))
'''


def probe_functions():
    cases = {}
    for name, nparams in FUNCTIONS:
        cases[name] = [[cost, credits][:nparams] for cost, credits in TEST_PAIRS]
    try:
        p = subprocess.run(
            [sys.executable, "-c", FUNCTION_PROBE, HERE, json.dumps(cases)],
            stdin=subprocess.DEVNULL, capture_output=True, text=True, encoding="utf-8",
            errors="replace", cwd=HERE, env=child_env(), timeout=RUN_SECONDS,
        )
    except subprocess.TimeoutExpired:
        return {"import": "timeout", "detail": "", "functions": {}}
    for line in p.stdout.splitlines():
        if "@@REPORT@@" in line:
            return json.loads(line.split("@@REPORT@@", 1)[1])
    last = (p.stderr.strip().splitlines() or ["unknown problem"])[-1]
    return {"import": "error", "detail": last, "functions": {}}


AMOUNT = re.compile(r"(?<![\d.])\d[\d,]*\.\d{2}(?![\d])")


def amounts_in(text):
    return {a.replace(",", "") for a in AMOUNT.findall(text)}


def last_error_line(stderr):
    lines = [l for l in stderr.strip().splitlines() if l.strip()]
    return lines[-1].strip() if lines else "unknown error"


def explain_crash(stderr):
    err = last_error_line(stderr)
    hints = ["Python said: " + err]
    if err.startswith("EOFError"):
        hints.append("Your program asked for more input than expected. Ask for cost and credits")
        hints.append("once, before the menu, and make Q end the loop.")
    elif "ValueError" in err and "int()" in err:
        hints.append("The yearly cost can have cents (like 9876.54). Convert it with float(), not int().")
    elif "unsupported operand" in err and "'str'" in err:
        hints.append("input() always gives back text. Convert it with float() or int() before doing math.")
    elif "NoneType" in err:
        hints.append("One of your functions gave back None. Make each function return its answer.")
    elif "of type 'str'" in err:
        hints.append("One of your functions gave back text. Return the number; format it only when printing.")
    elif err.startswith("NameError"):
        hints.append("Check the spelling and capitals of every name. Copy names from the template.")
    elif err.startswith(("SyntaxError", "IndentationError")):
        hints.append("Look at the line number in the message, and the line just above it.")
    return hints


