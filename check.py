RESULTS = []   # (status, label, [hint lines], blocking, (earned, possible) or None)
POINTS_POSSIBLE = 40
NOTES_OUT = []


def record(ok, label, hints=None, blocking=True, pts=None):
    RESULTS.append(("PASS" if ok else "FAIL", label, hints or [], blocking,
                    (pts if ok else 0, pts) if pts else None))
    return ok


def record_partial(label, earned, possible, hints=None):
    ok = earned == possible
    RESULTS.append(("PASS" if ok else "FAIL", label, hints or [], True, (earned, possible)))
    return ok


def skip(label, why, pts=None):
    RESULTS.append(("SKIP", label, [why], True, (0, pts) if pts else None))


def heading(text):
    RESULTS.append(("HEAD", text, [], False, None))


def points_earned():
    return sum(r[4][0] for r in RESULTS if r[4])


